import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'

const css = readFileSync(resolve(import.meta.dirname, '../../../../web/style.css'), 'utf8')

describe('sidebar text colors', () => {
  it('keeps a separate active token for the sidebar foreground', () => {
    // 断言 token 存在并被正确引用，不锁死具体色值，否则换主题就会整片变红。
    expect(css).toMatch(/--biu-color-text-muted:\s*[^;]+;/)
    expect(css).toMatch(/--biu-color-text:\s*[^;]+;/)
    expect(css).toMatch(/--biu-color-icon:\s*[^;]+;/)
    expect(css).toMatch(/--biu-color-icon:\s*[^;]+;/)
    expect(css).toMatch(/\.app-side-actions-icon\s*\{[^}]*color:\s*var\(--biu-color-icon\)/s)
    expect(css).toMatch(/\.app-side-bar\s*\{[^}]*color:\s*var\(--biu-color-text-muted\)/s)
    expect(css).toMatch(/--biu-color-bg-hover-subtle:\s*color-mix\(in srgb, #fff 9%, var\(--biu-color-bg-subtle\)\)/)
    expect(css).toMatch(/\.app-side-bar\s*\{[^}]*--biu-color-bg-hover:\s*var\(--biu-color-bg-hover-subtle\)/s)
    expect(css).toMatch(/\.chat-session-row\.is-active\s*\{[^}]*color:\s*var\(--biu-color-text\)/s)
    expect(css).toMatch(/\.chat-session-row\s*\{[^}]*-webkit-user-drag:\s*none/s)
  })

  it('left-aligns the sidebar brand with the list below', () => {
    expect(css).toMatch(/\.app-side-bar-head-brand\s*\{[^}]*justify-content:\s*flex-start/s)
    expect(css).toMatch(/\.app-side-bar-head-brand\s*\{[^}]*padding-left:\s*8px/s)
    expect(css).not.toMatch(/\.app-side-bar\.is-narrow \.app-side-bar-head-brand/)
  })

  it('session rows do not start a native drag ghost', () => {
    const sidebar = readFileSync(resolve(import.meta.dirname, './chat-sidebar.tsx'), 'utf8')
    expect(sidebar).toMatch(/draggable=\{false\}/)
    expect(sidebar).toMatch(/onDragStart=\{\(event\) => event.preventDefault\(\)\}/)
  })

  it('hides labels until the chat sidebar is wide enough', () => {
    expect(css).toMatch(/\.sidebar-label,\s*\.app-side-actions-label\s*\{[^}]*font-size:\s*var\(--biu-font-size-4\)/s)
    expect(css).toMatch(/\.sidebar-tag\s*\{[^}]*font-size:\s*11px/s)
    expect(css).toMatch(/\.sidebar-tag\s*\{[^}]*line-height:\s*16px/s)
    expect(css).toMatch(/\.sidebar-chat-count-num\s*\{[^}]*font-size:\s*var\(--biu-font-size-2\)/s)
    expect(css).toMatch(/\.sidebar-section-head\s*\{[^}]*font-size:\s*var\(--biu-font-size-2\)/s)
    expect(css).toMatch(/\.sidebar-view-switch-btn\s*\{[^}]*color:\s*var\(--biu-color-icon\)/s)
    expect(css).toMatch(/\.app-side-bar:not\(\.is-wide\) \.sidebar-tag/)
    const sidebar = readFileSync(resolve(import.meta.dirname, './chat-sidebar.tsx'), 'utf8')
    expect(sidebar).toMatch(/text-\[12px\] font-bold tracking-wider/)
    expect(sidebar).not.toMatch(/sidebar-section-head[\s\S]*?sidebar-label[\s\S]*?\{section\.label\}/)
    const frame = readFileSync(resolve(import.meta.dirname, './shell-sidebar-frame.tsx'), 'utf8')
    expect(sidebar).toMatch(/text-\[14px\]/)
    expect(frame).toMatch(/data-testid="sidebar-expand"/)
    expect(frame).toMatch(/visible && narrow/)
    expect(frame).toMatch(/function ShellRailHead/)
    expect(frame).toMatch(/useActiveWorkspaceLocation/)
    expect(frame).toMatch(/CloudIcon/)
    expect(frame).toMatch(/ComputerDesktopIcon/)
    expect(frame).not.toMatch(/BrandMark/)
    expect(css).toMatch(/\.shell-rail-head\s*\{/)
    expect(css).toMatch(/\.shell-rail-expand:hover \.shell-rail-expand-chevron/)
    expect(frame).not.toMatch(/data-dock-tip="展开"/)
    expect(frame).not.toMatch(/shell-rail-expand[\s\S]*?title="展开左侧边栏"/)
    expect(frame).toMatch(/function RailHoverTip/)
    expect(frame).toMatch(/createPortal/)
    expect(css).toMatch(/\.shell-rail-tip\s*\{/)
    expect(frame).toMatch(/data-testid="sidebar-resize"/)
    expect(frame).toMatch(/onWidthChange && !narrow/)
    expect(css).toMatch(/\.app-side-bar\.is-narrow \.sidebar-resize\s*\{[^}]*pointer-events:\s*none/s)
    expect(frame).toMatch(/onWidthLive/)
    expect(frame).toMatch(/if \(!drag\) return/)
    expect(frame).not.toMatch(/if \(!drag \|\| narrow\)/)
    expect(frame).toMatch(/if \(onWidthLive\) onWidthLive\(next\)/)
    expect(frame).toMatch(/shellColumnStartWidth\(event\.currentTarget, 'left'/)
    expect(frame).toMatch(/pointercancel/)
    expect(frame).not.toMatch(/getBoundingClientRect\(\)\.width/)
    const inspector = readFileSync(resolve(import.meta.dirname, './session-inspector.tsx'), 'utf8')
    expect(inspector).toMatch(/shellColumnStartWidth\(event\.currentTarget, 'inspector'/)
    expect(inspector).toMatch(/pointercancel/)
    const shell = readFileSync(resolve(import.meta.dirname, './index.tsx'), 'utf8')
    expect(shell).toMatch(/leftWidth: leftPane \? sidebarCol/)
    expect(shell).toMatch(/id="shell-module-sidebar"/)
    expect(shell).toMatch(/ShellSidebarFrame/)
    expect(shell).toMatch(/SIDEBAR_TAG_AT/)
    expect(shell).toMatch(/data-testid="header-sidebar-expand"/)
    expect(shell).toMatch(/leftHidden \? \(/)
    const overlay = readFileSync(resolve(import.meta.dirname, './chat-overlay.ts'), 'utf8')
    expect(overlay).toMatch(/SIDEBAR_LABEL_AT = SIDEBAR_MIN/)
    expect(overlay).toMatch(/SIDEBAR_TAG_AT = SIDEBAR_MAX/)
    expect(overlay).toMatch(/SIDEBAR_MIN = 160/)
    expect(css).toMatch(/--biu-sidebar-min:\s*160px/)
    expect(css).toMatch(/\.app-side-bar\s*\{[^}]*min-width:\s*0/s)
  })
})
