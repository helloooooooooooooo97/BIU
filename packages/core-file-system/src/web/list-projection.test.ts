import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { test } from 'vitest'
import assert from 'node:assert/strict'

test('table list and previews pass view columns to /api/db/list', () => {
  const browser = readFileSync(resolve(import.meta.dirname, './browser.tsx'), 'utf8')
  const client = readFileSync(resolve(import.meta.dirname, './db-client.ts'), 'utf8')
  const host = readFileSync(resolve(import.meta.dirname, '../host/index.ts'), 'utf8')
  const fields = readFileSync(resolve(import.meta.dirname, './fields.ts'), 'utf8')
  const preview = readFileSync(resolve(import.meta.dirname, './sidebar-preview.ts'), 'utf8')
  const people = readFileSync(resolve(import.meta.dirname, './person-cell.tsx'), 'utf8')
  const links = readFileSync(resolve(import.meta.dirname, './record-link-cell.tsx'), 'utf8')
  assert.match(browser, /listProjectionKeys/)
  assert.match(browser, /columns: listColumns/)
  assert.match(browser, /columnKeys.length \? columnKeys : schemaDefaultKeys/)
  assert.match(browser, /retainSavedColumn/)
  assert.match(browser, /groupListKeys\(cachedSchema, reqGroupBy/)
  assert.doesNotMatch(browser, /cachedSchema \? groupListKeys/)
  assert.match(browser, /Object.keys\(chrome.cells\)/)
  assert.match(browser, /LIST_SEED_COLUMNS/)
  assert.match(browser, /key !== 'tags'/)
  assert.doesNotMatch(browser, /'tags',\s*'dueAt'/)
  assert.doesNotMatch(host, /ensureColumn\(ensureColumn\(spec\.schema\.columns, 'facet'\), 'tags'\)/)
  assert.doesNotMatch(browser, /if \(chrome\?\.cells\) return undefined/)
  assert.match(browser, /\/api\/db\/read\?path=/)
  assert.match(client, /if \(opts\.columns\?\.length\) params\.set\('columns'/)
  assert.match(client, /opts.sorts.map\(\(item\) => \(\{ field: item.field, dir: item.dir \}\)\)/)
  assert.match(host, /columns: parseListColumnsParam\(route\.query\.get\('columns'\)\)/)
  assert.match(host, /listedColumnKeys\(page\?\.columns, schema\.labelField \?\? 'title', schema\)/)
  assert.match(host, /for \(const key of actionWhenKeys\(schema\)\) add\(key\)/)
  assert.match(fields, /for \(const key of actionWhenKeys\(opts\.schema\)\) add\(key\)/)
  assert.match(browser, /listReadySent\.current \? '暂无记录' : ''/)
  assert.match(browser, /if \(paintedPath !== dataPath\)/)
  assert.match(browser, /nodes: EMPTY_HOLD_NODES/)
  assert.match(browser, /tableHoldRef.current = tablePaintSnapshotRef.current \?\? emptyListHold/)
  assert.match(browser, /held\?\.nodes \?\? tablePaintNodes/)
  assert.doesNotMatch(browser, /reloadKey = .*listColumnsKey/)
  assert.match(browser, /collectQueryFields\(sorts, filterTree/)
  assert.match(browser, /flattenFacetColumns\(facetCatalog\)\.map\(\(item\) => \(\{/)
  assert.match(preview, /const columns = \['title', 'emoji', 'mascot', 'parentId'\]/)
  assert.match(preview, /columns: previewColumns\(view\)/)
  assert.match(people, /columns: \['title', 'mascot'\]/)
  assert.match(links, /columns: \['label'\]/)
})
